package academy.devdojo.maratonajava.javacore.Dconstrutores;

public class Construtores {
    /**
     * Construtores:
     *
     *     São usados para inicializar objetos no momento em que são criados.
     *
     *     Possuem o mesmo nome da classe e não possuem tipo de retorno.
     *
     *     Exemplo:
     *
     *         public Pessoa(String nome) {
     *             this.nome = nome;
     *         }
     *
     *     Criação:
     *
     *         Pessoa pessoa = new Pessoa("Mauricio");
     *
     *     this:
     *
     *         Refere-se ao objeto atual.
     *
     *     Construtor padrão:
     *
     *         Se nenhum construtor for declarado, o Java fornece
     *         um construtor sem argumentos.
     *
     *     Porém, quando um construtor é declarado explicitamente,
     *     o construtor padrão deixa de ser criado automaticamente.
     *
     *     Construtores também podem ser sobrecarregados.
     */
}
