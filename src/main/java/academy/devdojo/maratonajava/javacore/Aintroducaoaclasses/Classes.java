package academy.devdojo.maratonajava.javacore.Aintroducaoaclasses;

public class Classes {
    /**
     * Classes:
     *
     *     Uma classe é um modelo usado para criar objetos.
     *
     *     Ela pode definir:
     *
     *         - atributos → características/estado do objeto
     *         - métodos → comportamentos do objeto
     *
     *     Sintaxe:
     *
     *         public class Pessoa {
     *             String nome;
     *             int idade;
     *         }
     *
     *     Objeto:
     *
     *         Pessoa pessoa = new Pessoa();
     *
     *     A classe define a estrutura.
     *     O objeto é uma instância dessa classe.
     *
     *     new:
     *
     *         Cria uma nova instância da classe.
     *
     *     Exemplo:
     *
     *         Pessoa pessoa = new Pessoa();
     *
     *         Pessoa → tipo
     *         pessoa → referência
     *         new Pessoa() → cria o objeto
     */
}
