package academy.devdojo.maratonajava.javacore.Jmodificadorfinal.test;

public class Final {
    /**
     * final:
     *
     *     Impede alterações dependendo de onde é utilizado.
     *
     *     Variável final:
     *
     *         Não pode receber outro valor depois de inicializada.
     *
     *         final int NUMERO = 10;
     *
     *     Método final:
     *
     *         Não pode ser sobrescrito por subclasses.
     *
     *         public final void metodo() {}
     *
     *     Classe final:
     *
     *         Não pode ser herdada.
     *
     *         public final class Classe {}
     *
     *     Resumo:
     *
     *         final variável → não pode ser reatribuída
     *         final método   → não pode ser sobrescrito
     *         final classe   → não pode ser herdada
     */
}
