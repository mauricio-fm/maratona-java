package academy.devdojo.maratonajava.javacore.Isobrescrita.test;

public class Sobrescrita {
    /**
     * Sobrescrita de métodos (Override):
     *
     *     Acontece quando uma subclasse fornece uma nova implementação
     *     para um método herdado da superclasse.
     *
     *     Exemplo:
     *
     *         class Animal {
     *             public void emitirSom() {}
     *         }
     *
     *         class Cachorro extends Animal {
     *             @Override
     *             public void emitirSom() {}
     *         }
     *
     *     @Override:
     *
     *         Indica ao compilador que o método está sobrescrevendo
     *         um método herdado.
     *
     *     A assinatura compatível é necessária.
     *
     *     Sobrescrita está diretamente relacionada ao polimorfismo.
     *
     *     Override ≠ Overload
     *
     *         Override → redefine um método herdado.
     *         Overload  → mesmo nome, parâmetros diferentes.
     */
}
