package academy.devdojo.maratonajava.javacore.Bintroducaometodos;

public class Metodos {
    /**
     * Métodos:
     *
     *     Métodos representam comportamentos de uma classe.
     *
     *     Sintaxe:
     *
     *         modificador tipoRetorno nomeMetodo(parametros) {
     *             // código
     *         }
     *
     *     Exemplo:
     *
     *         public void imprimirNome(String nome) {
     *             System.out.println(nome);
     *         }
     *
     *     void:
     *
     *         Indica que o método não retorna um valor.
     *
     *     Parâmetros:
     *
     *         São valores recebidos pelo método.
     *
     *     return:
     *
     *         Retorna um valor quando o método possui um tipo de retorno.
     *
     *     Exemplo:
     *
     *         public int somar(int a, int b) {
     *             return a + b;
     *         }
     *
     *     Chamada:
     *
     *         int resultado = somar(10, 20);
     */
}
