package academy.devdojo.maratonajava.javacore.Gassosiacao;

public class Assosiacao {
    /**
     * Associação:
     *
     *     Representa uma relação entre objetos.
     *
     *     Um objeto pode possuir uma referência para outro objeto.
     *
     *     Exemplo:
     *
     *         class Professor {
     *             private Aluno aluno;
     *         }
     *
     *     Professor possui uma referência para Aluno.
     *
     *     Tipos comuns de relação:
     *
     *         - um para um
     *         - um para muitos
     *         - muitos para um
     *         - muitos para muitos
     *
     *     A associação representa uma relação entre classes,
     *     mas as classes continuam sendo tipos independentes.
     *
     *     Exemplo conceitual:
     *
     *         Professor → Aluno
     *         Departamento → Funcionários
     */
}
