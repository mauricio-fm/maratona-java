package academy.devdojo.maratonajava.javacore.Eblocoinicialização;

public class BlocoInicializacao {
    /**
     * Bloco de inicialização:
     *
     *     É um bloco de código executado durante a criação de uma instância,
     *     antes do construtor.
     *
     *     Sintaxe:
     *
     *         {
     *             // código
     *         }
     *
     *     Exemplo:
     *
     *         {
     *             System.out.println("Bloco de inicialização");
     *         }
     *
     *         public Pessoa() {
     *             System.out.println("Construtor");
     *         }
     *
     *     Ordem simplificada:
     *
     *         1. Inicialização da classe (static)
     *         2. Inicialização da instância
     *         3. Construtor
     *
     *     Em herança, a inicialização da classe pai acontece antes
     *     da inicialização da classe filha.
     */
}
