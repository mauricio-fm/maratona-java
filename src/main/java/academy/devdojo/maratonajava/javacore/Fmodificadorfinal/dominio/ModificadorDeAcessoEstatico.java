package academy.devdojo.maratonajava.javacore.Fmodificadorfinal.dominio;

public class ModificadorDeAcessoEstatico {
    /**
     * static:
     *
     *     Indica que um membro pertence à classe e não a uma instância específica.
     *
     *     Pode ser usado em:
     *
     *         - atributos
     *         - métodos
     *         - blocos de inicialização
     *
     *     Atributo static:
     *
     *         private static int contador;
     *
     *         Existe uma única variável compartilhada pelas instâncias.
     *
     *     Método static:
     *
     *         public static void imprimir() {}
     *
     *         Pode ser chamado através da classe:
     *
     *         Classe.imprimir();
     *
     *     Um método static não pode acessar diretamente atributos
     *     ou métodos de instância, pois não possui um objeto específico.
     *
     *     static → pertence à classe
     *     não static → pertence à instância
     */
}
